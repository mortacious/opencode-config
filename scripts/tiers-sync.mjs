#!/usr/bin/env node
// tiers-sync.mjs - expand a profile's authored model tiers into its overlay.
//
// A profile may carry profiles/<name>/tiers.json (strict JSON). Tier names are
// profile data: any non-empty set is allowed, and each entry carries the model
// ref plus a one-line description of the work it suits.
//
//   {
//     "tiers":  { "<tier name>": { "model": "<provider>/<model>[#variant]",
//                                  "description": "<one line>" }, ... },
//     "agents": { "<agent name>": "<tier name>", ... }
//   }
//
// This tool validates that file and regenerates profiles/<name>/opencode.jsonc
// as a GENERATED overlay: one literal agents.<name>.model pin per entry plus
// small_model set from the model of the "title" agent's tier. Consumers
// (profile-switcher) keep reading literal provider/model[#variant]
// strings from the overlay, so the overlay stays the source of literal pins
// and tiers.json is the authored source of the mapping.
//
// Usage:
//   node scripts/tiers-sync.mjs --profile <name>          # sync one profile
//   node scripts/tiers-sync.mjs --all                     # sync every tier profile
//   node scripts/tiers-sync.mjs --check --profile <name>  # report drift, exit 1
//   node scripts/tiers-sync.mjs --check --all
//
// Exit codes: 0 ok, 1 validation/write failure or drift, 2 usage error.
// TIERS_SYNC_ROOT=<dir> overrides the config root (tests operate on a copy).
//
// Dependency-free (Node stdlib only). All files ASCII only.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const DEFAULT_ROOT = path.resolve(HERE, '..');

// Built-in agents that may appear in tiers.json without an agents/<name>.md.
export const TIER_BUILTIN_AGENTS = new Set(['title']);
export const OVERLAY_SCHEMA = 'https://opencode.ai/config.json';
export const GENERATED_HEADER =
  '// GENERATED by scripts/tiers-sync.mjs from tiers.json - edit tiers.json, not this file.';

// ---------------------------------------------------------------------------
// Small helpers
// ---------------------------------------------------------------------------

function firstLine(text) {
  return String(text).split(/\r?\n/)[0].slice(0, 160);
}

function isFile(file) {
  try {
    return fs.statSync(file).isFile();
  } catch {
    return false;
  }
}

function rel(rootDir, file) {
  const r = path.relative(rootDir, file);
  return r === '' ? '.' : r.split(path.sep).join('/');
}

// ---------------------------------------------------------------------------
// Model refs: "<provider>/<model>" with an optional "#<variant>". No aliases.
// ---------------------------------------------------------------------------

export function parseModelRef(value) {
  if (typeof value !== 'string') return null;
  const ref = value.trim();
  const slash = ref.indexOf('/');
  if (slash <= 0 || slash === ref.length - 1) return null;
  const provider = ref.slice(0, slash).trim();
  let rest = ref.slice(slash + 1).trim();
  if (provider === '' || rest === '') return null;
  let variant = null;
  const hash = rest.indexOf('#');
  if (hash !== -1) {
    variant = rest.slice(hash + 1).trim();
    rest = rest.slice(0, hash).trim();
    if (rest === '' || variant === '') return null;
  }
  return { provider, model: rest, variant };
}

// ---------------------------------------------------------------------------
// Validation
// ---------------------------------------------------------------------------

export function loadAgentNames(rootDir) {
  const dir = path.join(rootDir, 'agents');
  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return [];
  }
  return entries
    .filter((entry) => entry.isFile() && entry.name.endsWith('.md'))
    .map((entry) => entry.name.slice(0, -3))
    .sort();
}

// Returns a list of human-readable errors; an empty list means valid.
export function validateTiersData(data, agentNames) {
  if (!data || typeof data !== 'object' || Array.isArray(data)) {
    return ['must be a JSON object with "tiers" and "agents"'];
  }
  const errors = [];
  for (const key of Object.keys(data)) {
    if (key !== 'tiers' && key !== 'agents') {
      errors.push(`unexpected top-level key "${key}"`);
    }
  }

  const tiers = data.tiers;
  const tierNames = [];
  // An empty model marks a tier unavailable in this profile and is allowed
  // only when no agent maps to it: a mapped tier would pin a literal "".
  const agentMapping =
    data.agents && typeof data.agents === 'object' && !Array.isArray(data.agents)
      ? data.agents
      : {};
  const mappedTiers = new Set(
    Object.values(agentMapping).filter((tier) => typeof tier === 'string'),
  );
  if (!tiers || typeof tiers !== 'object' || Array.isArray(tiers)) {
    errors.push('"tiers" must be an object');
  } else {
    const names = Object.keys(tiers);
    if (names.length === 0) errors.push('"tiers" is empty');
    for (const key of names) {
      tierNames.push(key);
      const entry = tiers[key];
      if (!entry || typeof entry !== 'object' || Array.isArray(entry)) {
        errors.push(`tier "${key}" must be an object with "model" and "description"`);
        continue;
      }
      if (typeof entry.model === 'string' && entry.model.trim() === '') {
        if (mappedTiers.has(key)) {
          errors.push(
            `tier "${key}" model is empty but agents map to it; a mapped tier needs <provider>/<model>[#variant]`,
          );
        }
      } else if (!parseModelRef(entry.model)) {
        errors.push(
          `tier "${key}" model ${JSON.stringify(entry.model)} is not <provider>/<model>[#variant]`,
        );
      }
      if (typeof entry.description !== 'string' || entry.description.trim() === '') {
        errors.push(`tier "${key}" description must be a non-empty string`);
      } else if (/[\r\n]/.test(entry.description)) {
        errors.push(`tier "${key}" description must be a single line`);
      }
    }
  }

  const agents = data.agents;
  const known = new Set(Array.isArray(agentNames) ? agentNames : []);
  if (!agents || typeof agents !== 'object' || Array.isArray(agents)) {
    errors.push('"agents" must be an object');
  } else {
    const names = Object.keys(agents);
    if (names.length === 0) errors.push('"agents" is empty');
    for (const name of names) {
      const tier = agents[name];
      if (typeof tier !== 'string' || !tierNames.includes(tier)) {
        errors.push(
          `agents.${name} must name an existing tier (got ${JSON.stringify(tier)})`,
        );
      }
      if (!known.has(name) && !TIER_BUILTIN_AGENTS.has(name)) {
        errors.push(`agents.${name} has no agents/${name}.md and is not a built-in`);
      }
    }
  }
  return errors;
}

// ---------------------------------------------------------------------------
// Expansion + rendering
// ---------------------------------------------------------------------------

// { agents: { <name>: "<provider>/<model>[#variant]" }, small_model? }
export function buildExpansion(data) {
  const tiers =
    data && data.tiers && typeof data.tiers === 'object' && !Array.isArray(data.tiers)
      ? data.tiers
      : {};
  const agents =
    data && data.agents && typeof data.agents === 'object' && !Array.isArray(data.agents)
      ? data.agents
      : {};
  const expansion = { agents: {} };
  for (const name of Object.keys(agents)) {
    const tier = tiers[agents[name]];
    const ref =
      tier && typeof tier === 'object' && typeof tier.model === 'string'
        ? tier.model.trim()
        : null;
    expansion.agents[name] = ref;
  }
  if (typeof expansion.agents.title === 'string') {
    expansion.small_model = expansion.agents.title;
  }
  return expansion;
}

export function renderOverlay(expansion) {
  const names = Object.keys(expansion.agents);
  const lines = [GENERATED_HEADER, '{', `  "$schema": ${JSON.stringify(OVERLAY_SCHEMA)},`];
  lines.push('  "agents": {');
  names.forEach((name, index) => {
    const comma = index === names.length - 1 ? '' : ',';
    lines.push(`    ${JSON.stringify(name)}: { "model": ${JSON.stringify(expansion.agents[name])} }${comma}`);
  });
  lines.push(expansion.small_model === undefined ? '  }' : '  },');
  if (expansion.small_model !== undefined) {
    lines.push(`  "small_model": ${JSON.stringify(expansion.small_model)}`);
  }
  lines.push('}');
  return lines.join('\n') + '\n';
}

// String-aware JSONC comment stripper (the generated header is a // comment;
// hand-edited overlays may also carry block comments).
export function stripJsonc(text) {
  let out = '';
  let inString = false;
  let escaped = false;
  for (let i = 0; i < text.length; i += 1) {
    const ch = text[i];
    if (inString) {
      out += ch;
      if (escaped) escaped = false;
      else if (ch === '\\') escaped = true;
      else if (ch === '"') inString = false;
      continue;
    }
    if (ch === '"') {
      inString = true;
      out += ch;
      continue;
    }
    if (ch === '/' && text[i + 1] === '/') {
      while (i < text.length && text[i] !== '\n') i += 1;
      if (i < text.length) out += '\n';
      continue;
    }
    if (ch === '/' && text[i + 1] === '*') {
      i += 2;
      while (i < text.length && !(text[i] === '*' && text[i + 1] === '/')) i += 1;
      i += 1;
      continue;
    }
    out += ch;
  }
  return out;
}

// Drift lines between an expansion and a parsed overlay config. Empty = match.
export function diffOverlay(expansion, config) {
  if (!config || typeof config !== 'object' || Array.isArray(config)) {
    return ['overlay is not a JSON object'];
  }
  const drifts = [];
  const allowed = new Set(['$schema', 'agents', 'small_model']);
  for (const key of Object.keys(config)) {
    if (!allowed.has(key)) {
      drifts.push(`unexpected top-level key "${key}" (a generated overlay carries only $schema, agents, small_model)`);
    }
  }
  if (config.$schema !== OVERLAY_SCHEMA) {
    drifts.push(`$schema is ${JSON.stringify(config.$schema)}, expected ${JSON.stringify(OVERLAY_SCHEMA)}`);
  }
  const actual = config.agents;
  if (actual !== undefined && (!actual || typeof actual !== 'object' || Array.isArray(actual))) {
    drifts.push('agents is not an object');
  } else {
    const actualAgents = actual || {};
    for (const name of Object.keys(expansion.agents)) {
      const want = expansion.agents[name];
      const entry = actualAgents[name];
      if (!entry || typeof entry !== 'object' || Array.isArray(entry)) {
        drifts.push(`agents.${name}.model is missing (expected ${JSON.stringify(want)})`);
      } else if (entry.model !== want) {
        drifts.push(`agents.${name}.model is ${JSON.stringify(entry.model)}, expected ${JSON.stringify(want)}`);
      }
    }
    for (const name of Object.keys(actualAgents)) {
      if (!Object.prototype.hasOwnProperty.call(expansion.agents, name)) {
        drifts.push(`agents.${name} is not generated from tiers.json`);
      }
    }
  }
  if (expansion.small_model === undefined) {
    if (config.small_model !== undefined) {
      drifts.push(`small_model is ${JSON.stringify(config.small_model)}, expected absence (no title agent)`);
    }
  } else if (config.small_model !== expansion.small_model) {
    drifts.push(`small_model is ${JSON.stringify(config.small_model)}, expected ${JSON.stringify(expansion.small_model)}`);
  }
  return drifts;
}

// ---------------------------------------------------------------------------
// Profile discovery + sync/check
// ---------------------------------------------------------------------------

export function listTierProfiles(rootDir) {
  const dir = path.join(rootDir, 'profiles');
  let entries;
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return [];
  }
  return entries
    .filter((entry) => entry.isDirectory() && isFile(path.join(dir, entry.name, 'tiers.json')))
    .map((entry) => entry.name)
    .sort();
}

function loadValidTiers(rootDir, name) {
  const tiersFile = path.join(rootDir, 'profiles', name, 'tiers.json');
  if (!isFile(tiersFile)) {
    throw new Error(`profiles/${name}/tiers.json is missing`);
  }
  let data;
  try {
    data = JSON.parse(fs.readFileSync(tiersFile, 'utf8'));
  } catch (error) {
    throw new Error(`${rel(rootDir, tiersFile)}: not valid JSON (${firstLine(error.message)})`);
  }
  const errors = validateTiersData(data, loadAgentNames(rootDir));
  if (errors.length > 0) {
    throw new Error(`${rel(rootDir, tiersFile)}: ${errors.join('; ')}`);
  }
  return { tiersFile, data };
}

export function syncProfile(rootDir, name) {
  const { data } = loadValidTiers(rootDir, name);
  const overlayFile = path.join(rootDir, 'profiles', name, 'opencode.jsonc');
  const text = renderOverlay(buildExpansion(data));
  let current = null;
  try {
    current = fs.readFileSync(overlayFile, 'utf8');
  } catch {
    current = null;
  }
  if (current === text) return { name, file: overlayFile, changed: false };
  const tmp = `${overlayFile}.tmp-${process.pid}`;
  try {
    fs.writeFileSync(tmp, text);
    fs.renameSync(tmp, overlayFile);
  } catch (error) {
    try {
      fs.rmSync(tmp, { force: true });
    } catch {
      // best effort
    }
    throw new Error(`cannot write ${rel(rootDir, overlayFile)}: ${firstLine(error.message)}`);
  }
  return { name, file: overlayFile, changed: true };
}

export function checkProfile(rootDir, name) {
  const { data } = loadValidTiers(rootDir, name);
  const overlayFile = path.join(rootDir, 'profiles', name, 'opencode.jsonc');
  let text;
  try {
    text = fs.readFileSync(overlayFile, 'utf8');
  } catch {
    return { name, file: overlayFile, drifts: ['overlay opencode.jsonc is missing'] };
  }
  let config;
  try {
    config = JSON.parse(stripJsonc(text));
  } catch (error) {
    return { name, file: overlayFile, drifts: [`overlay does not parse: ${firstLine(error.message)}`] };
  }
  return { name, file: overlayFile, drifts: diffOverlay(buildExpansion(data), config) };
}

// ---------------------------------------------------------------------------
// CLI
// ---------------------------------------------------------------------------

function printUsage() {
  console.error('Usage: node scripts/tiers-sync.mjs --profile <name> [--check]');
  console.error('       node scripts/tiers-sync.mjs --all [--check]');
}

function parseArgs(argv) {
  const opts = { check: false, all: false, profile: null, help: false };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === '--check') opts.check = true;
    else if (arg === '--all') opts.all = true;
    else if (arg === '--help' || arg === '-h') opts.help = true;
    else if (arg === '--profile') {
      const value = argv[i + 1];
      if (!value || value.startsWith('--')) throw new Error('--profile requires a profile name');
      opts.profile = value;
      i += 1;
    } else throw new Error(`unknown argument "${arg}"`);
  }
  if (opts.all && opts.profile !== null) {
    throw new Error('choose one of --profile <name> or --all');
  }
  return opts;
}

function syncMode(rootDir, names) {
  for (const name of names) {
    let result;
    try {
      result = syncProfile(rootDir, name);
    } catch (error) {
      console.error(`tiers-sync: ${name}: ${error.message}`);
      return 1;
    }
    console.log(`tiers-sync: ${rel(rootDir, result.file)} ${result.changed ? 'regenerated' : 'up to date'}`);
  }
  return 0;
}

function checkMode(rootDir, names) {
  let drifts = 0;
  for (const name of names) {
    let result;
    try {
      result = checkProfile(rootDir, name);
    } catch (error) {
      drifts += 1;
      console.error(`tiers-sync: ${name}: ${error.message}`);
      continue;
    }
    const label = rel(rootDir, result.file);
    if (result.drifts.length === 0) {
      console.log(`tiers-sync: ${label} ok`);
      continue;
    }
    for (const drift of result.drifts) {
      drifts += 1;
      console.error(`DRIFT ${label}: ${drift}`);
    }
  }
  console.log(`tiers-sync: ${names.length} profile(s) checked, ${drifts} drift(s)`);
  return drifts === 0 ? 0 : 1;
}

export function main(argv, rootDir) {
  const root = rootDir === undefined
    ? (process.env.TIERS_SYNC_ROOT ? path.resolve(process.env.TIERS_SYNC_ROOT) : DEFAULT_ROOT)
    : rootDir;
  let opts;
  try {
    opts = parseArgs(argv);
  } catch (error) {
    console.error(`tiers-sync: ${error.message}`);
    printUsage();
    return 2;
  }
  if (opts.help) {
    printUsage();
    return 0;
  }
  if (!opts.all && opts.profile === null) {
    console.error('tiers-sync: choose --profile <name> or --all');
    printUsage();
    return 2;
  }
  const names = opts.all ? listTierProfiles(root) : [opts.profile];
  if (names.length === 0) {
    console.error('tiers-sync: no profiles with tiers.json');
    return 1;
  }
  return opts.check ? checkMode(root, names) : syncMode(root, names);
}

const invokedPath = process.argv[1] ? path.resolve(process.argv[1]) : null;
if (invokedPath === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
